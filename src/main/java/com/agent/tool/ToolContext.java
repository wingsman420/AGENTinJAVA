package com.agent.tool;

import java.nio.file.Path;

/**
 * 一次工具调用所需的上下文。
 *
 * <p>目前只有工作目录一项，但把它单独拎出来而不是直接传 {@code Path}，是为了
 * 以后要加东西时（比如请求超时、调用方身份、取消信号）不必再改一遍所有工具的签名。
 *
 * <h2>为什么用显式参数，而不是 ThreadLocal</h2>
 * 工具需要知道"当前会话的工作目录"，而这个值随会话不同。
 *
 * <p>用 ThreadLocal 可以把目录隐式地"放在环境里"，不用改任何签名 —— 但代价是：
 * <ul>
 *   <li>依赖关系看不见了：读工具类时无法从签名判断它需要什么</li>
 *   <li>靠约定维持：谁忘了设置、谁忘了清理，编译器都不会提醒</li>
 *   <li>多线程下容易串味：虽然当前 ReAct 循环是同步的，但一旦引入异步就会出问题</li>
 * </ul>
 *
 * <p>显式传参改动了接口（三个工具 + 测试里的假工具），但换来的是
 * **编译器保证不可能忘记传**。这个交换在安全相关的参数上尤其值得 ——
 * 工作目录决定了路径沙箱的边界，传错一个会话的目录意味着越权访问。
 *
 * @param workspace 本次调用所属会话的工作目录，文件工具只能访问它以内的路径
 */
public record ToolContext(Path workspace) {
}
